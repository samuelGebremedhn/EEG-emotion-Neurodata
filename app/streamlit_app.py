from pathlib import Path
import sys
import io
import numpy as np
import streamlit as st
import matplotlib.pyplot as plt
import joblib

ROOT=Path(__file__).resolve().parents[1]; sys.path.insert(0,str(ROOT/'src'))
from eeg_emotion.config import Config
from eeg_emotion.features import extract_features

st.set_page_config(page_title='EEG Emotion Lab',layout='wide')
st.title('EEG Emotion-State Classification Lab')
st.caption('Educational portfolio demo — not a clinical diagnostic tool.')

cfg=Config.from_yaml(ROOT/'configs/default.yaml')
model_path=st.sidebar.text_input('Model path','models/logistic_regression_valence_subject.joblib')
upload=st.file_uploader('Upload a NumPy .npz window file',type=['npz'])
if upload:
    z=np.load(io.BytesIO(upload.getvalue()),allow_pickle=False); X=z['X']; st.write(f'Windows: {X.shape[0]} | Channels: {X.shape[1]} | Samples: {X.shape[2]}')
    i=st.slider('Window',0,len(X)-1,0); fig,ax=plt.subplots(figsize=(12,4)); ax.plot(X[i].T); ax.set_xlabel('Sample'); ax.set_ylabel('Amplitude'); st.pyplot(fig)
    try:
        bundle=joblib.load(ROOT/model_path); F,_=extract_features(X[i:i+1],cfg.sampling_rate,cfg.bands); pred=int(bundle['model'].predict(F)[0]); prob=float(bundle['model'].predict_proba(F)[0,1]) if hasattr(bundle['model'],'predict_proba') else None
        st.metric('Predicted class', 'High' if pred else 'Low')
        if prob is not None: st.metric('P(High)',f'{prob:.3f}')
    except Exception as e: st.warning(f'Load a compatible trained model: {e}')
else:
    st.info('Upload a prepared .npz file generated by prepare_deap.py or generate_demo_data.py.')
